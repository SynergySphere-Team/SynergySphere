export interface CareerProfileContext {
  userName: string;
  email: string;
  role: string;
  skillsList: string;
  skillsArray: [string, number][];
  projects: Array<{
    title: string;
    description: string | null;
    projectLink: string | null;
    githubLink: string | null;
  }>;
  level: number;
  xp: number;
}

